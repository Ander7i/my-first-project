def product_by_code(code: str) -> Product | None:
    return next((p for p in PRODUCTS if p.code == code), None)


def check_by_code(code: str) -> CheckType | None:
    return next((c for c in CHECKS if c.code == code), None)


def checks_for_product(product_code: str) -> tuple[CheckType, ...]:
    return tuple(c for c in CHECKS if c.product == product_code)


def product_titles() -> tuple[str, ...]:
    return tuple(p.title for p in PRODUCTS)


def validate() -> None:
    """Проверяет целостность каталога. Вызывается при старте бота."""
    product_codes = {p.code for p in PRODUCTS}
    if len(product_codes) != len(PRODUCTS):
        raise RuntimeError("В PRODUCTS есть повторяющиеся коды")

    check_codes = {c.code for c in CHECKS}
    if len(check_codes) != len(CHECKS):
        raise RuntimeError("В CHECKS есть повторяющиеся коды")

    for check in CHECKS:
        if check.product not in product_codes:
            raise RuntimeError(
                f"Проверка {check.code!r} ссылается на продукт "
                f"{check.product!r}, которого нет в PRODUCTS"
            )
        if check.needs_ack and not check.ack_text:
            raise RuntimeError(
                f"У проверки {check.code!r} стоит needs_ack, но нет ack_text"
            )
        if not check.checklist:
            raise RuntimeError(f"У проверки {check.code!r} пустой чек-лист")

    for product in PRODUCTS:
        if not checks_for_product(product.code):
            raise RuntimeError(
                f"У продукта {product.code!r} нет ни одной проверки"
            )
