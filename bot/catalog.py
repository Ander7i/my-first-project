@dataclass(frozen=True)
class Product:
    code: str
    title: str
    summary: str


@dataclass(frozen=True)
class CheckType:
    code: str
    product: str
    title: str
    summary: str
    duration: str
    # Проверку можно сделать из любого города (звонок, онлайн-заявка).
    remote: bool
    # Что делает исполнитель, по шагам.
    steps: tuple[str, ...]
    # Что нужно иметь, чтобы взяться.
    requirements: tuple[str, ...]
    # О чём человек должен знать до того, как возьмёт задание.
    warnings: tuple[str, ...] = ()
    # Вопросы, которые бот задаст при сдаче отчёта.
    checklist: tuple[str, ...] = ()
    # Что приложить к отчёту помимо ответов.
    attachments: tuple[str, ...] = ()
    # Нужно ли исполнителю действующее ИП: True — обязательно, False —
    # обязательно НЕ иметь, None — неважно.
    requires_ip: bool | None = None
    # Требует отдельного осознанного подтверждения перед взятием задания.
    needs_ack: bool = False
    ack_text: str = ""
    # Сколько дней должно пройти, прежде чем человек возьмёт такую проверку
    # снова. 0 — без ограничения.
    cooldown_days: int = 0
    # Через сколько дней после приёмки отчёта напомнить о деле, которое
    # осталось за человеком (закрыть ИП и счёт). 0 — напоминать не нужно.
    followup_days: int = 0
    followup_text: str = ""
    # Сколько раз всего человек может взять такую проверку. 0 — без лимита.
    # Нужно там, где каждое повторение что-то стоит человеку: запись в
    # кредитной истории, непогашенный займ, упёршийся в законный лимит.
    max_per_user: int = 0
    tags: tuple[str, ...] = field(default_factory=tuple)


